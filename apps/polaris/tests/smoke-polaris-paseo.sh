#!/usr/bin/env bash

set -euo pipefail

SCRIPT_NAME="$(basename "$0")"

log() {
  printf '[%s] %s\n' "$SCRIPT_NAME" "$*"
}

if ! command -v kubectl >/dev/null 2>&1; then
  log "Skipping: kubectl is not available"
  exit 0
fi

log "Rendering Polaris workspace manifest"
pnpm --dir apps/polaris run polaris -- render demo@pod

log "Reading Polaris workspace status"
pnpm --dir apps/polaris run polaris -- status demo@pod

test -f config/generated/pod/demo.yaml
grep -q "Generated by polaris.ts" config/generated/pod/demo.yaml
grep -q "POLARIS_WORKSPACE_DATA_ROOT" config/generated/pod/demo.yaml

log "polaris smoke test passed"
