function isRecord(value: unknown): value is Record<string, unknown> {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

export function coerceAdminPortalLocale(value: string | null | undefined): AdminPortalLocale {
  return value === "en-US" ? "en-US" : "zh-CN";
}

function resolvePath(tree: MessageTree, path: string): unknown {
  return path.split(".").reduce<unknown>((current, segment) => {
    if (!isRecord(current)) return undefined;
    return current[segment];
  }, tree);
}

export function formatAdminPortalMessage(
  template: string,
  values: Record<string, string | number | boolean> = {},
): string {
  return template.replace(/\{(\w+)\}/g, (_, key) => (
    key in values ? String(values[key]) : `{${key}}`
  ));
}

export function getAdminPortalMessage(
  locale: AdminPortalLocale,
  path: string,
): unknown {
  const selected = resolvePath(ADMIN_PORTAL_MESSAGES[locale], path);
  if (selected !== undefined) return selected;
  return resolvePath(ADMIN_PORTAL_MESSAGES[ADMIN_PORTAL_DEFAULT_LOCALE], path);
}

export function getAdminPortalText(
  locale: AdminPortalLocale,
  path: string,
  values?: Record<string, string | number | boolean>,
  fallback?: string,
): string {
  const value = getAdminPortalMessage(locale, path);
  if (typeof value === "string") return formatAdminPortalMessage(value, values);
  if (fallback !== undefined) return formatAdminPortalMessage(fallback, values);
  return path;
}

export function getAdminPortalList(
  locale: AdminPortalLocale,
  path: string,
  fallback: string[] = [],
): string[] {
  const value = getAdminPortalMessage(locale, path);
  return Array.isArray(value) ? value.map(String) : fallback;
}

export function translateAdminPortalInline(
  locale: AdminPortalLocale,
  source: string,
  values?: Record<string, string | number | boolean>,
): string {
  const template = locale === "en-US"
    ? (ADMIN_PORTAL_INLINE_TRANSLATIONS_EN[source] ?? source)
    : source;
  return formatAdminPortalMessage(template, values);
}

export function translateAdminPortalInlineText(
  locale: AdminPortalLocale,
  source: string,
): string {
  if (locale !== "en-US") return source;
  const exact = ADMIN_PORTAL_INLINE_TRANSLATIONS_EN[source];
  if (exact) return exact;

  for (const item of INLINE_TEMPLATE_PATTERNS) {
    const match = source.match(item.pattern);
    if (!match) continue;
    const values = Object.fromEntries(
      item.valueNames.map((name, index) => [name, match[index + 1] ?? ""]),
    );
    return formatAdminPortalMessage(item.target, values);
  }

  return source;
}
