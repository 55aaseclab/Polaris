const INLINE_TEMPLATE_PATTERNS = Object.entries(ADMIN_PORTAL_INLINE_TRANSLATIONS_EN)
  .filter(([key]) => key.includes("{"))
  .map(([key, target]) => {
    const valueNames: string[] = [];
    const escaped = key.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    const patternSource = escaped.replace(/\\\{(\w+)\\\}/g, (_, name: string) => {
      valueNames.push(name);
      return "(.+?)";
    });
    return {
      key,
      pattern: new RegExp(`^${patternSource}$`),
      target,
      valueNames,
    } satisfies InlineTemplatePattern;
  });

