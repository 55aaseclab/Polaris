#!/usr/bin/env bash

set -euo pipefail

SCRIPT_NAME="$(basename "$0")"

log() {
  printf '[%s] %s\n' "$SCRIPT_NAME" "$*"
}

if ! command -v kubectl >/dev/null 2>&1; then
  log "Skipping: kubectl is not available"
  exit 0
fi

if ! kubectl get runtimeclass kata-qemu >/dev/null 2>&1; then
  log "Skipping: kata-qemu runtimeclass is not available"
  exit 0
fi

log "Rendering Polaris workspace manifest"
pnpm exec tsx scripts/polaris.ts render morpheus

log "Reading Polaris workspace status"
pnpm exec tsx scripts/polaris.ts status morpheus

test -f config/generated/pod/morpheus.yaml
grep -q "Generated by polaris.ts" config/generated/pod/morpheus.yaml
grep -q "POLARIS_WORKSPACE_DATA_ROOT" config/generated/pod/morpheus.yaml

log "polaris smoke test passed"
